"""FastAPI application served on 127.0.0.1 by the Electron main process."""

from __future__ import annotations

import os

import rdkit
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse
from pydantic import BaseModel

from . import chem


class AnalyzeRequest(BaseModel):
    smiles: str = ""
    molfile: str | None = None


def create_app(token: str | None = None) -> FastAPI:
    """Build the app. When `token` is set every request must carry it."""
    app = FastAPI(
        title="Zephyrlea local backend",
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
    )

    @app.middleware("http")
    async def require_token(request: Request, call_next):
        # Loopback HTTP is reachable by any local process, so a shared secret
        # generated by the Electron main process guards every endpoint.
        if token and request.headers.get("x-zephyrlea-token") != token:
            return JSONResponse({"detail": "invalid token"}, status_code=401)
        return await call_next(request)

    @app.get("/health")
    def health() -> dict:
        return {
            "status": "ok",
            "engine": "rdkit",
            "rdkitVersion": rdkit.__version__,
            "pid": os.getpid(),
        }

    @app.post("/analyze")
    def analyze(body: AnalyzeRequest) -> dict:
        return chem.inspect_structure(body.smiles, body.molfile)

    return app
